ok("last day",                format(max(runs$day)), "2025-06-23")

cat("\n== weekday distribution (SI S3) ==\n")
wd <- table(factor(weekdays(unique(d[, .(day)])$day),
                   levels = c("Monday","Tuesday","Wednesday","Thursday","Friday")))
ok("Mon/Tue/Wed/Thu/Fri", as.integer(wd), c(8L, 39L, 48L, 50L, 58L))

cat("\n== hour of day (SI S3) ==\n")
ok("% between 9 am and 2 pm", round(100 * mean(d$hr >= 9 & d$hr < 14), 1), 88.6, 0.05)
frac <- d[, .(pct = round(100 * .N / nrow(d), 1)), by = hr][order(hr)]
ok("hours present (MST)", frac$hr, 7:16)
ok("hourly fractions", frac$pct,
   c(0.1, 2.8, 12.2, 19.3, 21.1, 20.6, 15.4, 6.2, 1.7, 0.6), 0.05)

cat("\n== pairwise correlations (SI S3) ==\n")
P <- c("Benzene_ppb","Toluene_ppb","Trimethylbenzene_ppb","Xylene_ppb",
       "Hydrogen_Sulfide_ppb","Hydrogen_Cyanide_ppb")
for (s in sort(unique(d$Site))) {
  cr <- cor(as.matrix(d[Site == s, ..P]), use = "pairwise.complete.obs")
  tag <- if (grepl("Suncor", s)) "Suncor" else "Holly "
  if (tag == "Suncor") {
    ok("Suncor toluene-xylene",      round(cr[2,4], 2), 0.94, 0.005)
    ok("Suncor TMB-xylene",          round(cr[3,4], 2), 0.90, 0.005)
    ok("Suncor benzene-TMB",         round(cr[1,3], 2), 0.70, 0.005)
  } else {
    ok("Holly toluene-xylene",       round(cr[2,4], 2), 0.84, 0.005)
    ok("Holly TMB-xylene",           round(cr[3,4], 2), 0.88, 0.005)
    ok("Holly toluene-TMB",          round(cr[2,3], 2), 0.75, 0.005)
  }
  cat(sprintf("       %s max |r| of H2S/HCN vs the aromatics: %.3f\n",
              tag, max(abs(cr[5:6, 1:4]))))
}

cat("\n== Table S3.1 and the claims that quote it ==\n")
cat("  Table S3.1 itself is generated by R_scripts/70_table_s31.R, which writes\n")
cat("  TABLE_S3.1.csv. If that file is present, check the text against it.\n")
tf <- file.path(BASE, "TABLE_S3.1.csv")
if (!file.exists(tf)) {
  cat("  [SKIP] TABLE_S3.1.csv not found - run R_scripts/70_table_s31.R first.\n")
} else {
  s <- fread(tf)
  setkey(s, pollutant)
  ok("benzene below MDL (Results 3.1)",  round(s["Benzene", pct_belowMDL]), 93)
  ok("H2S below MDL (Results 3.1)",      round(s["H2S",     pct_belowMDL]), 98)
  ok("HCN below MDL (Results 3.1)",      round(s["HCN",     pct_belowMDL]), 96)
  five <- s[pollutant != "HCN"]
  ok("analysis-set values, 5 pollutants (millions)",
     round(range(five$analysis) / 1e6, 2), c(1.44, 1.54), 0.005)
  # H2S now spans 199 days: the 2026-08-22 run retains it across the 2023 inlet
  # window, which affected the Eiger aromatics but not the Picarro. TMB is the
  # floor at 159. If H2S drops back to ~164 the retention has been undone.
  ok("sampling days, 5 pollutants",      range(five$n_days), c(159L, 199L))
  ok("H2S sampling days (2023 window retained)", s["H2S", n_days], 199L)
  # These four move when 03_checks_flags.R changes what HCN it keeps. They are
  # reported against what the documents currently state rather than asserted, so
  # a re-run tells you exactly which sentences to update instead of just failing.
  # 28-30 May 2025 is excluded as a calibration window, so HCN is 2 days and
  # 27,739 values below the previous run.
  DOC <- list(hcn_n = 478660L, hcn_days = 39L,
              hcn_from = "2025-01-22", hcn_to = "2025-06-23")
  cmp <- function(lab, got, doc) {
    same <- isTRUE(all.equal(got, doc, check.attributes = FALSE))
    cat(sprintf("  [%s] %-44s run %-14s documents say %s\n",
                if (same) "OK  " else "EDIT", lab,
                paste(format(got), collapse = ","), paste(format(doc), collapse = ",")))
  }
  cmp("HCN values",        s["HCN", analysis],                DOC$hcn_n)
  cmp("HCN sampling days", s["HCN", n_days],                  DOC$hcn_days)
  cmp("HCN window start",  as.character(s["HCN", first_day]), DOC$hcn_from)
  cmp("HCN window end",    as.character(s["HCN", last_day]),  DOC$hcn_to)
  ok("no value left without a published MDL", sum(s$n_no_mdl), 0L)
  cat("\n  maxima behind \"exceeded ...\" in Results 3.1 (ppb):\n")
  for (p in c("Benzene","Toluene","Xylene","Trimethylbenzene","H2S","HCN"))
    cat(sprintf("    %-18s max = %10.2f\n", p, s[p, max]))
}

