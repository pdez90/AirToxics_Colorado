# ==============================================================
# Audit of the numeric claims in the manuscript and SI against the
# pipeline's own outputs. Every number the text asserts about the
# measurement record is recomputed here from mobile_wswd.RData, so a
# re-run either reproduces the printed claim or shows what changed.
#
#   Rscript tests/audit_manuscript_claims.R
#
# CLAIM REFRESH (2026-09-25). The `claim` argument of every ok() call is what
# the DOCUMENTS say, so it has to move whenever they do. After the 300 m
# ATOPs-headquarters exclusion these were left on the pre-exclusion text and a
# clean run reported ten failures that were not failures - the documents were
# right and this file was stale. That is worse than no harness: it trains the
# reader to skim past FAIL. Refreshed below against the 25 Sep documents.
# The three correlation claims are the exception: those failures were real and
# are what caught SI S3 still quoting the submitted-era coefficients.
#
# Definitions follow 43_figure_s31_routes.R: the Goodrich route is
# excluded, and a "run" is one Site x calendar day.
#
# `date` is a fixed-MST wall clock carried with a UTC tzone attribute,
# so format(date, tz = "UTC") reads the MST clock directly. Do not
# convert it -- see REPRODUCIBILITY.md.
# ==============================================================
suppressPackageStartupMessages(library(data.table))

BASE <- Sys.getenv("SUNCOR_BASE", "~/Downloads/Suncor")
load(file.path(path.expand(BASE), "mobile_wswd.RData"))   # -> out
d <- as.data.table(out); rm(out)
stopifnot(attr(d$date, "tzone") == "UTC")
d <- d[Site != "Goodrich Corporation (Collins Aerospace)"]
d[, day := as.Date(date)]
d[, hr  := as.integer(format(date, "%H", tz = "UTC"))]
d[, ym  := as.integer(format(day, "%Y%m"))]

ok <- function(lab, got, want, tol = 0) {
  pass <- isTRUE(all.equal(got, want, tolerance = tol, check.attributes = FALSE))
  cat(sprintf("  [%s] %-46s got %-22s claim %s\n",
              if (pass) "OK  " else "FAIL", lab,
              paste(format(got), collapse = ","),
              paste(format(want), collapse = ",")))
  invisible(pass)
}

cat("\n== measurement record (Methods; Results 3.1) ==\n")
runs <- unique(d[, .(Site, day)])
ok("1-s measurements",        nrow(d),               2555285L)
ok("runs (Site x day)",       nrow(runs),            205L)
ok("unique sampling days",    uniqueN(runs$day),     203L)
